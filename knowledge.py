class SearchInput(BaseModel):
    """Запит до бази знань про вихідні."""

    model_config = ConfigDict(str_strip_whitespace=True)

    query: str = Field(description="Пошуковий запит українською, від 2 до 200 символів")

    @field_validator("query")
    @classmethod
    def query_length(cls, value: str) -> str:
        if not 2 <= len(value) <= 200:
            raise ValueError("Запит має містити від 2 до 200 символів")
        return value


# Службові слова не допомагають відрізнити документ. Префікс з чотирьох літер
# згладжує відмінки: «Львові» і «Львова» дають один і той самий ключ.
_STOPWORDS = {
    "або", "але", "без", "для", "його", "якщо", "коли", "між", "навіть", "нього",
    "після", "проти", "також", "того", "тоді", "тому", "через", "щоб", "який",
    "яка", "які", "цей", "ця", "це", "вже", "ще", "під", "над", "при", "про",
    "від", "із", "зі", "та", "до", "за", "на", "по", "не", "чи", "що",
}


def _features(text: str) -> set[str]:
    words = re.findall(r"[0-9a-zа-яіїєґ']+", text.casefold())
    found: set[str] = set()
    for word in words:
        if len(word) < 3 or word in _STOPWORDS:
            continue
        found.add(word[:4])
    return found


def _same_documents(collection) -> bool:
    ids = [f"doc_{index}" for index in range(len(DOCUMENTS))]
    if collection.count() != len(ids):
        return False
    got = collection.get(ids=ids)
    stored = dict(zip(got.get("ids") or [], got.get("documents") or []))
    return [stored.get(doc_id) for doc_id in ids] == DOCUMENTS


def get_collection():
    """Відкриває постійну колекцію і перезаписує її, якщо тексти змінились."""
    CHROMA_PATH.mkdir(parents=True, exist_ok=True)
    client = chromadb.PersistentClient(path=str(CHROMA_PATH))
    collection = client.get_or_create_collection(COLLECTION_NAME)
    if not _same_documents(collection):
        client.delete_collection(COLLECTION_NAME)
        collection = client.create_collection(COLLECTION_NAME)
        collection.add(
            documents=DOCUMENTS,
            ids=[f"doc_{index}" for index in range(len(DOCUMENTS))],
        )
    return collection


@tool(args_schema=SearchInput)
def search_knowledge(query: str) -> str:
    """Знайти довідку в базі знань про вихідні.

    Викликай, коли потрібні факти, орієнтири цін, сезон, транспорт, музеї
    або правило на випадок дефіциту бюджету. Не викликай, щоб додати вже
    відомі суми, і не викликай, щоб забронювати житло.

    Args:
        query: Про що шукати в базі знань.

    Returns:
        Топ-3 релевантних документи або повідомлення, що нічого не знайдено.
    """
    collection = get_collection()
    stored = [item for item in (collection.get().get("documents") or []) if item]
    if not stored:
        return "Нічого не знайдено в базі знань"
    # MiniLM слабко розрізняє українські тексти, тож відстань із Chroma лише
    # розрулює нічию. Спершу рахуємо збіг змістовних префіксів слів.
    queried = collection.query(
        query_texts=[query],
        n_results=len(stored),
        include=["documents", "distances"],
    )
    distance = {}
    for doc, dist in zip(queried["documents"][0], queried["distances"][0]):
        distance[doc] = dist
    query_features = _features(query)
    ranked = sorted(
        stored,
        key=lambda doc: (-len(query_features & _features(doc)), distance.get(doc, 1.0)),
    )
    return "\n---\n".join(ranked[:3])
